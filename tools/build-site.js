function textShingles(text, size = 8) {
  const value = String(text || "").replace(/[\s\p{P}\p{S}]+/gu, "");
  const shingles = new Set();
  for (let i = 0; i <= value.length - size; i += 1) shingles.add(value.slice(i, i + size));
  return shingles;
}

function shingleSimilarity(left, right) {
  const a = textShingles(left);
  const b = textShingles(right);
  if (!a.size || !b.size) return 0;
  let intersection = 0;
  for (const value of a) if (b.has(value)) intersection += 1;
  return intersection / (a.size + b.size - intersection);
}

