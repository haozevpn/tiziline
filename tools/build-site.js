function escapeHtml(value) {
  return String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function prefixFor(pathName) {
  if (pathName === "/") return "";
  const clean = pathName.replace(/^\/+|\/+$/g, "");
  const depth = clean.includes(".") ? clean.split("/").length - 1 : clean.split("/").length;
  return "../".repeat(depth);
}

function localHref(prefix, target) {
  if (target === "") return `${prefix}index.html`;
  if (target.endsWith("/")) return `${prefix}${target}index.html`;
  return `${prefix}${target}`;
}

function relink(html, prefix) {
  return html.replace(/(href|src)="\/([^"#?]*)"/g, (_, attribute, target) => `${attribute}="${localHref(prefix, target)}"`);
}

function pageLabel(pathName, title) {
  if (pathName === "/") return "首页";
  const category = editorialCategories.find((item) => pathName === `/${item.slug}/`);
  if (category) return category.title;
  const keywordPage = keywordPages.find((page) => pathName === `/${page.slug}/`);
  if (keywordPage) return keywordPage.title;
  if (pathName.startsWith("/rank")) return "机场排行";
  if (pathName.startsWith("/reviews")) return "机场测评";
  if (pathName.startsWith("/knowledge/") && pathName !== "/knowledge/") return title;
  if (pathName.startsWith("/knowledge")) return "科普知识";
  if (pathName.startsWith("/about")) return "关于我们";
  if (pathName.startsWith("/posts/")) return title;
  return title;
}

